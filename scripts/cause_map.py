def _match(rules, fallback, cause_norm):
    for group, kws in rules:
        for kw in kws:
            if kw in cause_norm:
                return group
    return fallback


def map_judgment(cat, cause_norm):
    """裁判書 (案類, 正規化 JTITLE) → 種類。
    家事先試非訟細項（較特定），再試訴訟分組；行政/懲戒不細分（保留原始案由供鑽取）"""
    if cat == '民事':
        return _match(CIVIL_RULES, CIVIL_FALLBACK, cause_norm)
    if cat == '家事':
        g = _match(FAMNONLIT_RULES, None, cause_norm)
        if g:
            return g
        return _match(FAMLIT_RULES, '其他家事', cause_norm)
    if cat in ('刑事', '少年'):
        return _match(CRIME_TITLE_RULES, CRIME_TITLE_FALLBACK, cause_norm)
    return cat or '其他'


def map_cause(file_type, cause_norm):
    """正規化後的案由 → 種類（file_type 不在表內時原樣回 '其他'）"""
    rules, fallback = _RULES_BY_TYPE.get(file_type, ((), '其他'))
    for group, kws in rules:
        for kw in kws:
            if kw in cause_norm:
                return group
    return fallback


