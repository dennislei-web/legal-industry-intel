def map_criminal(law, art, sub):
    """(法名, 條, 條之N) → (cause 顯示鍵, cause_group)
    例：('刑法','185','3') → ('刑法§185-3', '公共危險罪')
        ('洗錢防制法','14','') → ('洗錢防制法§14', '洗錢防制法')"""
    law = norm_cause(law)
    art = (art or '').strip()
    sub = (sub or '').strip()
    key = f'{law}§{art}' + (f'-{sub}' if sub else '') if art else law
    if law in ('刑法', '中華民國刑法'):
        try:
            n = int(art)
        except ValueError:
            return key, '其他普通刑法'
        # 319-1 以下（妨害性隱私）獨立成章
        if n == 319 and sub:
            return key, '妨害性隱私及不實性影像罪'
        for lo, hi, label in _PENAL_CHAPTERS:
            if lo <= n <= hi:
                return key, label
        return key, '其他普通刑法'
    return key, (law or '未填')


# ---------- 刑事：罪名條號 → 供給面種類（案由供需「刑事」頁，mig 264）----------
# 需求面（終結微資料）用條號對罪章／特別法名，供給面（裁判書）用標題關鍵字分 CRIME_TITLE_RULES
# 42 組，兩邊標籤不同。這裡把罪章／特別法名再套一次 CRIME_TITLE_RULES（特別法標題慣寫
# 「違反○○法」、罪章名與標題用字幾乎同源），得到與供給面同一把尺的種類。
# 罪章粒度天生對不上的三處用條號覆寫：殺人罪章 §276 是過失致死（2021-26 累計 7,927 人次 vs
# 殺人 §271 1,109）、背信及重利罪章 §344／344-1 是重利（1,040 vs 背信 §342 1,154）、
# 傷害罪章 §284 是過失傷害（2025 單年 19,459 vs 普通傷害 §277 11,156，佔傷害罪章 63%；
# 2026-11-05 拆出，與量體端 biz_line() 把 §284 算進交通刑事一致，見 mig 267）。
# 已知不硬修的落差：家暴傷害（供給面標題「家庭暴力防治法」→家庭暴力；需求面主罪名 §277→傷害）。
_CRIM_ARTICLE_OVERRIDES = {
    '276': '過失致死',
    '284': '過失傷害',
    '344': '重利', '344-1': '重利',
}


def map_criminal_supply(law, art, sub):
    """(法名, 條, 條之N) → (cause 顯示鍵, 罪章／特別法名, 供給面種類)
    例：('刑法','276','')      → ('刑法§276', '殺人罪', '過失致死')
        ('刑法','284','')      → ('刑法§284', '傷害罪', '過失傷害')
        ('洗錢防制法','14','') → ('洗錢防制法§14', '洗錢防制法', '洗錢防制法')
        ('性騷擾防治法','25','') → ('性騷擾防治法§25', '性騷擾防治法', '其他刑事')"""
    key, group = map_criminal(law, art, sub)
    if norm_cause(law) in ('刑法', '中華民國刑法'):
        a = (art or '').strip()
        if (sub or '').strip():
            a += f'-{sub.strip()}'
        if a in _CRIM_ARTICLE_OVERRIDES:
            return key, group, _CRIM_ARTICLE_OVERRIDES[a]
    return key, group, _match(CRIME_TITLE_RULES, CRIME_TITLE_FALLBACK, group)


