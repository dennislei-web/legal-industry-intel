def infer_cat(cause_norm):
    """案類判不出時從案由文字推回案類。回傳 (案類, 種類覆寫或 None)；推不回的回 ('其他', None)。"""
    c = cause_norm or ''
    if RE_INFER_CONST.search(c):
        return '其他', CONST_GROUP
    if RE_INFER_CRIM.search(c):
        return '刑事', None
    if RE_INFER_ADMIN.search(c):
        return '行政', None
    if RE_INFER_LAWNAME.search(c):
        return '行政', None
    if RE_INFER_FAM.search(c):
        return '家事', None
    if RE_INFER_CIV.search(c):
        return '民事', None
    if c.startswith('違反') or re.search(r'(法|條例)等$', c):
        return '刑事', None
    if c.endswith('等'):
        return '行政', None
    return '其他', None


def resolve_judgment(cat, cause_norm):
    """(案類, 正規化案由) → (有效案類, 種類)。judgment_stats.sync_cause_map 用這個寫 cause_group_map 的 cat／cause_group：
    案類判得出的照 map_judgment；判不出（'其他'／空）的先 infer_cat 推回案類再分組，憲法法庭聲請獨立成種類，
    推不回的留 ('其他', '其他')。複合鍵 ck 的前綴不變（lawyer_month_stats.causes 的鍵），下游統計一律讀 cause_group_map.cat。"""
    if cat in KNOWN_CATS:
        return cat, map_judgment(cat, cause_norm)
    new_cat, override = infer_cat(cause_norm)
    if override:
        return '其他', override
    if new_cat in KNOWN_CATS:
        return new_cat, map_judgment(new_cat, cause_norm)
    return '其他', '其他'
