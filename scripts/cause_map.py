import re

# ---------- 正規化 ----------

_FULL2HALF = str.maketrans('（）０１２３４５６７８９', '()0123456789')


def norm_cause(s):
    """全形括號/數字轉半形、去空白與控制字元（實測月包偶有 \\x00，Postgres text 不收）；
    保留「等」字（不影響關鍵字比對）"""
    s = (s or '').translate(_FULL2HALF)
    s = re.sub(r'[\s　\x00-\x1f\x7f]', '', s)
    return s or '未填'


