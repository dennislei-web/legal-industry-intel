-- 前端：產業分析＞商標專利 tab 底部「併購觀察名單」卡（admin 才載入）。

BEGIN;

CREATE TABLE IF NOT EXISTS ip_watchlist (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  firm text NOT NULL UNIQUE,          -- 對齊 tipo_firm_stats.firm（名簿歸戶名）
  tier text NOT NULL CHECK (tier IN ('1','2','3','4','X')),  -- 1核心/2體量/3商標交叉/4後備/X排除
  note text,                          -- 人工判讀備註（主事者/訊號/DD 重點）
  sort int NOT NULL DEFAULT 0
);

ALTER TABLE ip_watchlist ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS ip_watchlist_admin_read ON ip_watchlist;
CREATE POLICY ip_watchlist_admin_read ON ip_watchlist
  FOR SELECT TO authenticated USING (
    EXISTS (SELECT 1 FROM user_profiles WHERE id = auth.uid() AND role = 'admin')
  );

COMMENT ON TABLE ip_watchlist IS '專利事務所併購觀察名單（admin 限定；tier 1核心/2體量/3商標交叉/4後備/X排除）';

