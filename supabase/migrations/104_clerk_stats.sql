-- 書記官是司法量能先行指標（直接影響結案速度/開庭排程）；2026-03 全國缺額 353 人
-- （缺額率 10.02%，新北 71/士林 29/北院 23/高院·中院各 24——聯合報 2026-05 報導，
--   立法院/司法院對外說明，無常規統計表，僅前端靜態引用）。
--
-- 資料源：
-- * clerk_staff_stats / clerk_court_snapshot＝司法統計年報（114 年報 lp-2475）各機關
--   「員工實有人數」ODS，scripts/clerk_staff_stats.py 解析（欄位口徑見該腳本 docstring：
--   clerks＝書記官長＋兼科長/股長＋書記官，不含錄事與會計/統計室課員；judges＝含院長/
--   庭長/候補/優遇）。年底數。112 年高行 +103 人＝行政訴訟堅實第一審新制（地方庭併入）。
-- * clerk_exam_stats＝司法特考四等書記官（公職王/高點彙整，108-114 兩源交叉一致；
--   104-107 需用名額無公開資料留 NULL）。錄取率 4.31%(104)→25.59%(114) 是人力荒
--   供給端訊號：報考降 + 需用暴增。
-- 年更：年報每年 6-7 月出（換 LP_ID 重跑腳本）；考試 8 月放榜後手動 INSERT。

CREATE TABLE IF NOT EXISTS clerk_staff_stats (
  year_roc int NOT NULL,
  org text NOT NULL,         -- 審級/機關（地方法院/高等法院及分院/…/司法院/法官學院）
  total_staff int,           -- 員工總計（含工友技工駕駛）
  judges int,                -- 法官（含院長/庭長/候補/優遇）
  clerks int,                -- 書記官（書記官長＋兼科長/股長＋書記官）
  PRIMARY KEY (year_roc, org)
);

CREATE TABLE IF NOT EXISTS clerk_court_snapshot (
  year_roc int NOT NULL,
  court text NOT NULL,       -- 個別法院（地院 23＋高院及分院 6）
  total_staff int,
  judges int,
  clerks int,
  PRIMARY KEY (year_roc, court)
);

CREATE TABLE IF NOT EXISTS clerk_exam_stats (
  year_roc int PRIMARY KEY,  -- 司法特考四等書記官
  applicants int,            -- 報考
  takers int,                -- 到考
  quota_regular int,         -- 需用（正額）
  quota_extra int,           -- 需用（增額）
  final_pass int,            -- 錄取
  pass_rate numeric          -- 錄取率 %
);

ALTER TABLE clerk_staff_stats ENABLE ROW LEVEL SECURITY;
ALTER TABLE clerk_court_snapshot ENABLE ROW LEVEL SECURITY;
ALTER TABLE clerk_exam_stats ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "read_css" ON clerk_staff_stats;
CREATE POLICY "read_css" ON clerk_staff_stats FOR SELECT USING (true);
DROP POLICY IF EXISTS "read_ccs" ON clerk_court_snapshot;
CREATE POLICY "read_ccs" ON clerk_court_snapshot FOR SELECT USING (true);
DROP POLICY IF EXISTS "read_ces" ON clerk_exam_stats;
CREATE POLICY "read_ces" ON clerk_exam_stats FOR SELECT USING (true);
GRANT SELECT ON clerk_staff_stats, clerk_court_snapshot, clerk_exam_stats TO anon, authenticated;

